-- Screen shader effects: frozen zoom and colour inversion.
--
-- Hyprland has exactly one screen-shader slot (decoration:screen_shader), so
-- both effects are generated into a single shader by this module:
--
--   * Frozen zoom. Hyprland renders cursor:zoom_factor only on the monitor
--     under the pointer. When you jump away from a magnified monitor it would
--     snap back to 100%, so the shader re-creates the same magnified view there,
--     targeting that output alone through the wl_output uniform. Jumping back
--     removes it and Hyprland's own zoom takes over.
--   * Colour inversion (CTRL + ALT + I by default): every output, all pixels.
--
-- If something else (a per-window inversion plugin, a user shader) already
-- owns the slot, both effects are skipped with one notification and that
-- shader is left alone.
--
-- State lives in $XDG_RUNTIME_DIR so it survives a config reload and is gone
-- after a reboot. While any view is frozen the shader references the `time`
-- uniform, which makes Hyprland render full frames continuously (the frozen
-- view keeps updating, a video keeps playing in it). That costs GPU time and
-- battery and stops as soon as nothing is frozen; inversion alone does not
-- need it.
return function(mag)
  local cfg = mag.settings
  local FROZEN_FILE = mag.runtime .. "/omarchy-magnifier-frozen" -- lines: <output id> <zoom> <cx> <cy>
  local INVERT_FLAG = mag.runtime .. "/omarchy-magnifier-inverted" -- exists -> colours inverted
  local SHADER_FILE = mag.runtime .. "/omarchy-magnifier.frag"
  local warned_foreign = false

  local function read_frozen()
    local frozen = {}
    local f = io.open(FROZEN_FILE, "r")
    if not f then return frozen end
    for line in f:lines() do
      local id, zoom, cx, cy = line:match("^(%d+)%s+([%d.]+)%s+([%d.]+)%s+([%d.]+)")
      if id then frozen[tonumber(id)] = { zoom = tonumber(zoom), cx = tonumber(cx), cy = tonumber(cy) } end
    end
    f:close()
    return frozen
  end

  local function write_frozen(frozen)
    local any = false
    local f = io.open(FROZEN_FILE, "w")
    if not f then return end
    local ids = {}
    for id in pairs(frozen) do ids[#ids + 1] = id end
    table.sort(ids)
    for _, id in ipairs(ids) do
      local e = frozen[id]
      f:write(string.format("%d %.4f %.5f %.5f\n", id, e.zoom, e.cx, e.cy))
      any = true
    end
    f:close()
    if not any then os.remove(FROZEN_FILE) end
  end

  local function inverted()
    return mag.file_exists(INVERT_FLAG)
  end

  -- Same box Hyprland's own zoom uses: rigid keeps the pointer centred, loose
  -- (the default) keeps the point under the pointer where it is on screen.
  local function generate(frozen, invert)
    local rigid = hl.get_config("cursor.zoom_rigid") and true or false
    local any_frozen = next(frozen) ~= nil
    local lines = {
      "#version 300 es",
      "// Generated by the Omarchy Magnifier plugin - do not edit.",
      "precision highp float;",
      "in vec2 v_texcoord;",
      "uniform sampler2D tex;",
      "uniform int wl_output;",
    }
    if any_frozen then lines[#lines + 1] = "uniform float time;" end
    lines[#lines + 1] = "out vec4 fragColor;"
    lines[#lines + 1] = "void main() {"
    lines[#lines + 1] = "  vec2 uv = v_texcoord;"
    local ids = {}
    for id in pairs(frozen) do ids[#ids + 1] = id end
    table.sort(ids)
    for _, id in ipairs(ids) do
      local e = frozen[id]
      local origin = rigid
        and string.format("vec2(%.5f, %.5f) - 0.5 / z", e.cx, e.cy)
        or string.format("vec2(%.5f, %.5f) * (1.0 - 1.0 / z)", e.cx, e.cy)
      lines[#lines + 1] = string.format(
        "  if (wl_output == %d) { float z = %.4f; vec2 o = clamp(%s, vec2(0.0), vec2(1.0 - 1.0 / z)); uv = o + uv / z; }",
        id, e.zoom, origin)
    end
    lines[#lines + 1] = "  vec4 color = texture(tex, uv);"
    if invert then lines[#lines + 1] = "  color.rgb = 1.0 - color.rgb;" end
    if any_frozen then lines[#lines + 1] = "  if (time < -1.0) color = vec4(0.0); // keeps the time uniform alive" end
    lines[#lines + 1] = "  fragColor = color;"
    lines[#lines + 1] = "}"
    return table.concat(lines, "\n") .. "\n"
  end

  local function current_shader()
    local v = hl.get_config("decoration.screen_shader")
    if type(v) ~= "string" then return "" end
    return v
  end

  -- True when the slot is free or already ours; warns once when it is not.
  local function slot_available(what)
    local cur = current_shader()
    if cur == "" or cur == SHADER_FILE then return true end
    if what and not warned_foreign then
      warned_foreign = true
      mag.notify("Magnifier: another screen shader is active, so " .. what .. " is unavailable")
    end
    return false
  end

  local M = {}

  function M.apply()
    local frozen = read_frozen()
    local invert = inverted()
    if not slot_available() then return end
    -- Clearing first forces Hyprland to recompile even though the path is unchanged.
    hl.config({ decoration = { screen_shader = "" } })
    if next(frozen) == nil and not invert then return end
    local f = io.open(SHADER_FILE, "w")
    if not f then return end
    f:write(generate(frozen, invert))
    f:close()
    hl.config({ decoration = { screen_shader = SHADER_FILE } })
  end

  -- Keep monitor `id` showing a magnified view: zoom factor `zoom` around the
  -- normalised point (cx, cy) in 0..1 monitor coordinates.
  function M.freeze(id, zoom, cx, cy)
    if not slot_available("keeping monitors you leave magnified") then return false end
    local frozen = read_frozen()
    frozen[id] = { zoom = zoom, cx = math.max(0, math.min(1, cx)), cy = math.max(0, math.min(1, cy)) }
    write_frozen(frozen)
    M.apply()
    return true
  end

  function M.unfreeze(id)
    local frozen = read_frozen()
    if frozen[id] == nil then return end
    frozen[id] = nil
    write_frozen(frozen)
    M.apply()
  end

  function M.unfreeze_all()
    os.remove(FROZEN_FILE)
    M.apply()
  end

  function M.frozen(id)
    return read_frozen()[id]
  end

  M.inverted = inverted

  -- action: "on" | "off" | "toggle" | "status". Returns "inverted" or "normal".
  function M.set_invert(action)
    action = action or "toggle"
    local function state() return inverted() and "inverted" or "normal" end
    if action == "status" then return state() end
    local want
    if action == "on" then want = true
    elseif action == "off" then want = false
    else want = not inverted() end
    if want == inverted() then return state() end
    if want and not slot_available("colour inversion") then return state() end
    if want then
      local f = io.open(INVERT_FLAG, "w")
      if f then f:close() end
    else
      os.remove(INVERT_FLAG)
    end
    M.apply()
    hl.exec_cmd("omarchy osd -m " .. mag.shell_quote(want and "Colours inverted" or "Colours normal"))
    return state()
  end

  -- A config reload resets decoration.screen_shader, so re-apply whatever is
  -- on file every time the config loads.
  M.apply()

  mag.screenfx = M
  mag.api.unfreeze_all = M.unfreeze_all
  mag.api.invert = M.set_invert

  if cfg.invert then
    mag.bind(cfg.keys.invert, "Magnifier invert colours", function() M.set_invert("toggle") end)
  elseif inverted() then
    -- Feature switched off while the flag is set: drop the inversion.
    os.remove(INVERT_FLAG)
    M.apply()
  end
end
